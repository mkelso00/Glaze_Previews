function escapeHtml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

// URL for a project's raw primary file (each path segment encoded).
function rawUrl(primary) {
  return "/" + primary.split("/").map(encodeURIComponent).join("/");
}

