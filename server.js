// Minimal zero-dependency static server for hosting HTML previews.
//
// Railway's default static serving injects a restrictive Content-Security-Policy
// that blocks the blob:/data: URLs and new Function() eval that Claude Code
// "bundled page" exports rely on, so previews render blank. This server serves
// the same files with a CSP that permits exactly what those bundles need, while
// still blocking plugins/framing of untrusted origins.

import { createServer } from "node:http";
import { createReadStream, readFileSync, existsSync } from "node:fs";
import { stat, mkdir, readFile, writeFile, rename } from "node:fs/promises";
import { join, normalize, extname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash, timingSafeEqual, randomUUID } from "node:crypto";

const ROOT = fileURLToPath(new URL(".", import.meta.url)).replace(/\/+$/, "");
const PORT = process.env.PORT || 3000;

// Clean-URL slug map, generated by scripts/build-index.mjs. Each entry maps a
// slug to its project's primary page and base folder, so previews are served at
// /<slug>/ (and their assets at /<slug>/<path>) instead of raw folder paths.
let SLUGS = new Map();
try {
  const manifest = JSON.parse(readFileSync(join(ROOT, "previews.json"), "utf8"));
  SLUGS = new Map(manifest.map((p) => [p.slug, p]));
} catch {
  /* no manifest yet — slug routing off, static serving still works */
}

